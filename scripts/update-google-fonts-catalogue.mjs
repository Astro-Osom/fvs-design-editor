#!/usr/bin/env node
/**
 * Regenerates src/fonts/google-catalogue.json: the list of Google Fonts families
 * the editor can offer. It holds names and available styles only, no font files.
 *
 *   node scripts/update-google-fonts-catalogue.mjs
 *
 * Sources (none needs an API key):
 * - https://fonts.google.com/metadata/fonts          families, categories, styles, popularity
 * - https://api.github.com/repos/google/fonts        the licence of each family, from the
 *                                                    folder it lives in (ofl/, apache/, ufl/)
 * - https://api.fontsource.org/v1/fonts?type=google  a second opinion on the licence
 *
 * A family is only listed when its licence was confirmed as one of the three open
 * licences Google Fonts uses. See docs/research/fonts.md.
 */
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'fonts', 'google-catalogue.json');
const HEADERS = { 'User-Agent': 'google-fonts-catalogue-script' };

const CATEGORY_CODES = { 'Sans Serif': 0, Serif: 1, Display: 2, Handwriting: 3, Monospace: 4 };
const LICENSES = ['OFL-1.1', 'Apache-2.0', 'UFL-1.0'];
const LICENSE_BY_FOLDER = { ofl: 'OFL-1.1', apache: 'Apache-2.0', ufl: 'UFL-1.0' };
const CJK_SUBSETS = ['chinese-simplified', 'chinese-traditional', 'chinese-hongkong', 'japanese', 'korean'];

async function getJson(url) {
  const response = await fetch(url, { headers: HEADERS });
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  const text = await response.text();
  // Google's metadata has sometimes been prefixed with ")]}'" to stop it being run as a script.
  return JSON.parse(text.replace(/^\)\]\}'\s*/, ''));
}

/** Family folder names in google/fonts are the family name in lower case without spaces. */
const folderName = (family) => family.toLowerCase().replace(/[^a-z0-9]/g, '');

async function licencesFromRepository() {
  const root = await getJson('https://api.github.com/repos/google/fonts/git/trees/main');
  const byFolder = new Map();
  for (const [folder, license] of Object.entries(LICENSE_BY_FOLDER)) {
    const entry = root.tree.find((item) => item.path === folder && item.type === 'tree');
    if (!entry) throw new Error(`google/fonts has no ${folder}/ folder any more`);
    const tree = await getJson(entry.url);
    if (tree.truncated) throw new Error(`The ${folder}/ listing was cut short`);
    for (const item of tree.tree) if (item.type === 'tree') byFolder.set(item.path, license);
  }
  return byFolder;
}

function weightMasks(fonts) {
  let normal = 0;
  let italic = 0;
  for (const key of Object.keys(fonts)) {
    const match = /^([1-9]00)(i?)$/.exec(key);
    if (!match) continue;
    const bit = 1 << (Number(match[1]) / 100 - 1);
    if (match[2]) italic |= bit;
    else normal |= bit;
  }
  return [normal, italic];
}

const [metadata, repoLicences, fontsource] = await Promise.all([
  getJson('https://fonts.google.com/metadata/fonts'),
  licencesFromRepository(),
  getJson('https://api.fontsource.org/v1/fonts?type=google'),
]);
const fontsourceLicence = new Map(fontsource.map((font) => [font.family, font.license]));

const families = [];
const skipped = [];
const disagreements = [];
for (const item of [...metadata.familyMetadataList].sort((a, b) => a.popularity - b.popularity)) {
  const category = CATEGORY_CODES[item.category];
  const [normal, italic] = weightMasks(item.fonts ?? {});
  const fromRepo = repoLicences.get(folderName(item.family));
  const fromFontsource = fontsourceLicence.get(item.family);
  const license = fromRepo ?? fromFontsource;
  if (fromRepo && fromFontsource && fromRepo !== fromFontsource) disagreements.push(`${item.family}: ${fromRepo} vs ${fromFontsource}`);
  if (item.isOpenSource === false || !LICENSES.includes(license)) {
    skipped.push(`${item.family} (licence not confirmed)`);
    continue;
  }
  if (category === undefined || normal === 0) {
    skipped.push(`${item.family} (no regular styles, or an unknown category)`);
    continue;
  }
  const large = item.subsets?.some((subset) => CJK_SUBSETS.includes(subset)) ? 1 : 0;
  families.push([item.family, category, normal, italic, LICENSES.indexOf(license), large]);
}

const catalogue = {
  note: 'Generated by scripts/update-google-fonts-catalogue.mjs. Names and styles only; font files are downloaded when a family is used.',
  generatedAt: new Date().toISOString().slice(0, 10),
  categories: Object.keys(CATEGORY_CODES),
  licenses: LICENSES,
  // [family, category, upright weights, italic weights, licence, large]
  // Weights are bit masks: bit 0 is 100, bit 8 is 900. Families are in order of popularity.
  families,
};
await writeFile(OUT, `${JSON.stringify(catalogue)}\n`);

console.log(`Wrote ${families.length} families to ${path.relative(process.cwd(), OUT)}`);
console.log(`Licences: ${LICENSES.map((l, i) => `${l} ${families.filter((f) => f[4] === i).length}`).join(', ')}`);
if (skipped.length) console.log(`Left out ${skipped.length}:\n  ${skipped.join('\n  ')}`);
if (disagreements.length) console.log(`Licence sources disagree for ${disagreements.length}:\n  ${disagreements.join('\n  ')}`);
